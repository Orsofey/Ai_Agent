_WEEKDAYS = ('понедельник', 'вторник', 'среда', 'четверг',
             'пятница', 'суббота', 'воскресенье')


def _pick(options):
    return random.choice(options)


def time_response():
    now = datetime.now()
    return f'Сейчас {now.hour} часов {now.minute:02d} минут' if now.minute else f'Сейчас {now.hour} часов ровно'


def date_response():
    now = datetime.now()
    return f'Сегодня {now.day} {_MONTHS[now.month - 1]}, {_WEEKDAYS[now.weekday()]}'


def greeting_by_hour():
    hour = datetime.now().hour
    if 5 <= hour < 12:
        return 'Доброе утро'
    if 12 <= hour < 18:
        return 'Добрый день'
    if 18 <= hour < 23:
        return 'Добрый вечер'
    return 'Доброй ночи'


