_COMPILED = [(re.compile(r'^(?:' + p + r')$', re.I), cat) for p, cat in _PATTERNS]


def match_casual(text):
    """Вернуть (категория, ответ) для разговорной фразы, иначе (None, None).

    Совпадение должно покрывать всю фразу (кроме завершающей пунктуации),
    чтобы не перехватывать настоящие команды.
    """
    phrase = re.sub(r'\s+', ' ', str(text or '')).strip().strip('.,!?…—-\u2014')
    if not phrase or len(phrase) > 120:
        return None, None

    # Время и дата — отвечаем мгновенно, локально.
    if re.match(r'^(который час|сколько времени|сколько сейчас времени|какое сейчас время|текущее время)$', phrase, re.I):
        return 'time', time_response()
    if re.match(r'^(какое сегодня число|какой сегодня день|какое сегодня число и день|какая сегодня дата|какое число|какой день недели)$', phrase, re.I):
        return 'date', date_response()

    for regex, category in _COMPILED:
        if regex.match(phrase):
            options = REPLIES[category]
            answer = random.choice(options)
            if category == 'greeting' and not re.search(r'привет|здравств|салют', answer, re.I):
                answer = f'{greeting_by_hour()}! {answer}'
            return category, answer
    return None, None


def is_casual(text):
    """Быстрая проверка: фраза является повседневной темой."""
    return match_casual(text)[0] is not None
